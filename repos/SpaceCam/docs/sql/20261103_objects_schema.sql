-- 7.1 Объекты: чтение — admin/владелец/соучастник
drop policy if exists objects_select on objects;
create policy objects_select on objects for select to authenticated
using (
  sc_is_admin()
  or owner_id = auth.uid()
  or exists (select 1 from object_participants op
             where op.object_id = id and op.user_id = auth.uid())
);

-- Вставка: любой аутентифицированный создаёт со себя; админ — на любого
drop policy if exists objects_insert on objects;
create policy objects_insert on objects for insert to authenticated
with check (owner_id = auth.uid() or sc_is_admin());

-- Обновление: admin/владелец/соучастник
drop policy if exists objects_update on objects;
create policy objects_update on objects for update to authenticated
using (
  sc_is_admin()
  or owner_id = auth.uid()
  or exists (select 1 from object_participants op
             where op.object_id = id and op.user_id = auth.uid())
)
with check (
  sc_is_admin()
  or owner_id = auth.uid()
  or exists (select 1 from object_participants op
             where op.object_id = id and op.user_id = auth.uid())
);

-- Удаление: admin/владелец
drop policy if exists objects_delete on objects;
create policy objects_delete on objects for delete to authenticated
using (sc_is_admin() or owner_id = auth.uid());

-- 7.2 Соучастники: чтение — все аутентифицированные; запись — только админ
