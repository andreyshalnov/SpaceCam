-- Дата: 03.11.2026. Запуск: Supabase → SQL Editor (или Management API /database/query).
-- Повторный запуск безопасен (IF NOT EXISTS / OR REPLACE / drop-if-exists+create).
--
-- Сущности:
--   object_types        — справочник типов объектов (14 значений из выгрузки 1С)
--   objects             — объекты строительства (ID вида М00090001…, стиль 1С)
--   object_participants — соучастники (полный доступ; назначает админ)
--   object_specs        — спецификации 1С (М00055086, источник, защита проекта)
--   object_spec_items   — номенклатура спецификаций (SKU, кол-во, ед., сумма)
--   app_settings        — настройки приложения (ключ DaData и пр.)
--   objects_overview    — витрина базовой информации для остальных пользователей
--
-- Доступ (по требованию владельца):
--   admin           — полный доступ ко всем объектам
--   владелец        — полный доступ к своим объектам
--   соучастник      — полный доступ к назначенным объектам
--   прочие (аутент.)— только базовая информация: ID, название, адрес, время создания
--   аноним          — доступа нет
-- ============================================================================

