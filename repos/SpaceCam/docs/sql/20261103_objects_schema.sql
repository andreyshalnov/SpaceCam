-- ---------------------------------------------------------------------------
-- 8. Витрина базовой информации (только ID, код, название, адрес, время создания)
--    Владелец витрины — postgres, RLS базовой таблицы не применяется:
--    это осознанное решение — «остальные пользователи видят только базовую информацию».
--    Анониму доступ запрещён (grant только authenticated).
-- ---------------------------------------------------------------------------
drop view if exists objects_overview;
create view objects_overview with (security_invoker = false) as
  select id, object_code, object_name, address, created_at
  from objects;

