-- ---------------------------------------------------------------------------
-- 2. Объекты строительства
-- ---------------------------------------------------------------------------
create table if not exists objects (
  id              uuid primary key default gen_random_uuid(),
  object_code     text unique,                          -- М00090001 (авто, стиль 1С)
  owner_id        uuid not null references profiles(id) on delete cascade,
  object_name     text not null,
  address         text not null default '',
  address_json    jsonb,                                -- структура адреса DaData
  type_id         int references object_types(id),
  deadline        date,                                 -- планируемый срок сдачи
  contractor      text not null default '',             -- контрагент
  status          text not null default 'Новый',
  summary         text not null default '',             -- суть проекта (гибрид)
  budget_amount   numeric(14,2),
  budget_currency text not null default 'RUB',
  spec            jsonb not null default '[]'::jsonb,   -- простой список позиций из формы
  entry_date      date,                                 -- дата внесения в базу (из 1С/CSV)
  verified        boolean not null default false,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

create index if not exists idx_objects_owner  on objects(owner_id);
create index if not exists idx_objects_status on objects(status);
create index if not exists idx_objects_type   on objects(type_id);

alter table objects drop constraint if exists objects_status_check;
alter table objects add constraint objects_status_check
  check (status in ('Новый', 'В работе', 'Реализация', 'Заморожен'));

alter table objects drop constraint if exists objects_currency_check;
alter table objects add constraint objects_currency_check
  check (budget_currency in ('RUB', 'USD', 'EUR', 'CNY'));

-- ---------------------------------------------------------------------------
-- 3. Соучастники (назначает админ в админке; владельцу и соучастнику — полный доступ)
-- ---------------------------------------------------------------------------
create table if not exists object_participants (
  object_id  uuid not null references objects(id) on delete cascade,
  user_id    uuid not null references profiles(id) on delete cascade,
  added_by   uuid,
  created_at timestamptz not null default now(),
  primary key (object_id, user_id)
);

-- ---------------------------------------------------------------------------
-- 4. Спецификации 1С + номенклатура
-- ---------------------------------------------------------------------------
create table if not exists object_specs (
  id         uuid primary key default gen_random_uuid(),
  object_id  uuid not null references objects(id) on delete cascade,
  spec_no    text not null unique,                      -- М00055086
  spec_date  timestamptz,
  source     text,                                      -- Проработка с нуля / Перевод с конкурента /
                                                        -- Входящий спрос / Собственное продвижение /
                                                        -- Проработка партнера
  protection text,                                      -- Получена защита проекта /
                                                        -- Отказ (защищено за другим поставщиком)
  qty        numeric(14,2),
  sum        numeric(14,2),
  created_at timestamptz not null default now()
);
create index if not exists idx_specs_object on object_specs(object_id);

create table if not exists object_spec_items (
  id      uuid primary key default gen_random_uuid(),
  spec_id uuid not null references object_specs(id) on delete cascade,
  name    text not null,                                -- номенклатура
  sku     text,                                         -- нормализованный код (стиль eW)
  qty     numeric(14,2) not null default 0,
  unit    text not null default 'шт',
  sum     numeric(14,2),
  sort    int not null default 0
);
create index if not exists idx_spec_items_spec on object_spec_items(spec_id);

-- ---------------------------------------------------------------------------
-- 5. Настройки приложения
-- ---------------------------------------------------------------------------
create table if not exists app_settings (
  key        text primary key,                          -- напр. 'dadata_api_key'
  value      text,
  updated_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- 6. Нумератор ID объектов (стиль 1С; диапазон с М00090001 — выше максимума
--    спецификаций из выгрузки М00085210, чтобы номера не пересекались)
-- ---------------------------------------------------------------------------
create sequence if not exists object_code_seq start 90001;

create or replace function sc_next_object_code() returns text
language plpgsql security definer set search_path = public as $$
begin
  return 'М' || lpad(nextval('object_code_seq')::text, 8, '0');
end $$;

-- авто-присвоение кода и статуса при вставке
create or replace function sc_objects_before_ins() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.object_code is null or new.object_code = '' then
    new.object_code := sc_next_object_code();
  end if;
  if new.status is null or new.status = '' then
    new.status := 'Новый';
  end if;
  return new;
end $$;

drop trigger if exists trg_objects_before_ins on objects;
create trigger trg_objects_before_ins before insert on objects
  for each row execute function sc_objects_before_ins();

-- updated_at автоматически
create or replace function sc_set_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

drop trigger if exists trg_objects_upd on objects;
create trigger trg_objects_upd before update on objects
  for each row execute function sc_set_updated_at();

